        public int GetMinPrice(string category, string meal)
        {
            const string sql =
                "SELECT MIN(t.Gia) FROM MonAn m LEFT JOIN ThongTinMon t ON t.IDMA = m.IDMA " +
                "WHERE COALESCE(t.Gia, 0) > 0 AND ($cat = '' OR COALESCE(t.LoaiMon, 'Món chính') = $cat) " +
                "AND ($meal = '' OR instr(',' || COALESCE(t.BuoiAn, 'Sáng,Trưa,Chiều,Tối') || ',', ',' || $meal || ',') > 0)";
            using (SqliteConnection connection = Open())
            using (SqliteCommand command = BuildCommand(connection, sql, ("$cat", category ?? string.Empty), ("$meal", meal ?? string.Empty)))
            {
                object value = command.ExecuteScalar();
                return value == null || value == DBNull.Value ? 0 : Convert.ToInt32(value);
            }
        }

