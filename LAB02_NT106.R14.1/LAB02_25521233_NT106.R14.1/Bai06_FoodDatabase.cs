        public bool DeleteContributor(int contributorId, bool moveDishesToLibrary)
        {
            using (SqliteConnection connection = Open())
            {
                if (moveDishesToLibrary)
                {
                    int systemId = FindOrCreateOwner(connection, SystemOwnerName, Roles.System);
                    ExecuteNonQuery(connection, "UPDATE MonAn SET IDNCC = $sys WHERE IDNCC = $id", ("$sys", systemId), ("$id", contributorId));
                }
                else
                {
                    using (SqliteCommand countCommand = BuildCommand(connection, "SELECT COUNT(*) FROM MonAn WHERE IDNCC = $id", ("$id", contributorId)))
                    {
                        if (Convert.ToInt32(countCommand.ExecuteScalar()) > 0)
                        {
                            return false;
                        }
                    }
                }

                ExecuteNonQuery(connection, "DELETE FROM NguoiDung WHERE IDNCC = $id AND QuyenHan <> $sysRole", ("$id", contributorId), ("$sysRole", Roles.System));
                return true;
            }
        }

