        private int FindOrCreateOwner(SqliteConnection connection, string fullName, string role)
        {
            using (SqliteCommand command = BuildCommand(connection, "SELECT IDNCC FROM NguoiDung WHERE HoVaTen = $name LIMIT 1", ("$name", fullName)))
            {
                object found = command.ExecuteScalar();
                if (found != null && found != DBNull.Value)
                {
                    return Convert.ToInt32(found);
                }
            }

            ExecuteNonQuery(connection, "INSERT INTO NguoiDung (HoVaTen, QuyenHan) VALUES ($name, $role)", ("$name", fullName), ("$role", role));
            return LastInsertId(connection);
        }

