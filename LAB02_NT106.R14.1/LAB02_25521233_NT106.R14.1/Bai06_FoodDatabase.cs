        public int EnsureCatalog()
        {
            if (GetSetting(CatalogVersionKey, string.Empty) == "done")
            {
                return 0;
            }

            int added = 0;
            using (SqliteConnection connection = Open())
            {
                int ownerId = FindOrCreateOwner(connection, SystemOwnerName, Roles.System);

                HashSet<string> existingNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
                using (SqliteCommand command = BuildCommand(connection, "SELECT TenMonAn FROM MonAn"))
                using (SqliteDataReader reader = command.ExecuteReader())
                {
                    while (reader.Read())
                    {
                        existingNames.Add(reader.GetString(0));
                    }
                }

                foreach (CatalogDish info in SampleInfo)
                {
                    if (!existingNames.Contains(info.Name))
                    {
                        continue;
                    }
                    ExecuteNonQuery(connection,
                        "INSERT OR IGNORE INTO ThongTinMon (IDMA, LoaiMon, BuoiAn, Gia, VungMien, MoTa) SELECT IDMA, $cat, $meals, $price, $region, $desc FROM MonAn WHERE TenMonAn = $name",
                        ("$cat", info.Category), ("$meals", info.Meals), ("$price", info.Price), ("$region", info.Region), ("$desc", info.Description), ("$name", info.Name));
                }

                foreach (CatalogDish dish in FoodCatalog.All)
                {
                    if (existingNames.Contains(dish.Name))
                    {
                        continue;
                    }

                    ExecuteNonQuery(connection, "INSERT INTO MonAn (TenMonAn, HinhAnh, IDNCC) VALUES ($name, '', $owner)", ("$name", dish.Name), ("$owner", ownerId));
                    int dishId = LastInsertId(connection);
                    ExecuteNonQuery(connection,
                        "INSERT INTO ThongTinMon (IDMA, LoaiMon, BuoiAn, Gia, VungMien, MoTa) VALUES ($id, $cat, $meals, $price, $region, $desc)",
                        ("$id", dishId), ("$cat", dish.Category), ("$meals", dish.Meals), ("$price", dish.Price), ("$region", dish.Region), ("$desc", dish.Description));
                    existingNames.Add(dish.Name);
                    added++;
                }
            }

            SetSetting(CatalogVersionKey, "done");
            return added;
        }

