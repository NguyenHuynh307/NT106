        public int CleanupAutoContributors()
        {
            if (GetSetting(CleanupVersionKey, string.Empty) == "done")
            {
                return 0;
            }

            int removed = 0;
            using (SqliteConnection connection = Open())
            {
                ExecuteNonQuery(connection, "PRAGMA synchronous = OFF");
                ExecuteNonQuery(connection, "UPDATE NguoiDung SET HoVaTen = $new, QuyenHan = $role WHERE HoVaTen = $old",
                    ("$new", SystemOwnerName), ("$role", Roles.System), ("$old", LegacySystemOwnerName));
                int systemId = FindOrCreateOwner(connection, SystemOwnerName, Roles.System);

                ExecuteNonQuery(connection, "BEGIN");
                {
                    foreach (string name in AutoGeneratedNames)
                    {
                        ExecuteNonQuery(connection, "UPDATE MonAn SET IDNCC = $sys WHERE IDNCC IN (SELECT IDNCC FROM NguoiDung WHERE HoVaTen = $name)", ("$sys", systemId), ("$name", name));
                        using (SqliteCommand command = BuildCommand(connection, "DELETE FROM NguoiDung WHERE HoVaTen = $name", ("$name", name)))
                        {
                            removed += command.ExecuteNonQuery();
                        }
                    }
                    ExecuteNonQuery(connection, "UPDATE MonAn SET HinhAnh = '' WHERE HinhAnh LIKE '%seed%.png'");
                    ExecuteNonQuery(connection, "COMMIT");
                }
            }

            SetSetting(CleanupVersionKey, "done");
            return removed;
        }

