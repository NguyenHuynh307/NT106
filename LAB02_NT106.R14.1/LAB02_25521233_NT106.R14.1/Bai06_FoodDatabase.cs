        {
            return DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss", CultureInfo.InvariantCulture);
        }

        private SqliteConnection Open()
        {
            SqliteConnection connection = new SqliteConnection(connectionString);
            connection.Open();
            return connection;
        }

        private SqliteCommand BuildCommand(SqliteConnection connection, string sql, params (string Name, object Value)[] parameters)
        {
            LastSql = string.Join(" ", sql.Split((char[])null, StringSplitOptions.RemoveEmptyEntries));

            SqliteCommand command = connection.CreateCommand();
            command.CommandText = sql;
            foreach ((string Name, object Value) parameter in parameters)
            {
                if (sql.Contains(parameter.Name))
                {
                    command.Parameters.AddWithValue(parameter.Name, parameter.Value ?? DBNull.Value);
                }
            }
            return command;
        }

        private void ExecuteNonQuery(SqliteConnection connection, string sql, params (string Name, object Value)[] parameters)
        {
            using (SqliteCommand command = BuildCommand(connection, sql, parameters))
            {
                command.ExecuteNonQuery();
            }
        }

        private int LastInsertId(SqliteConnection connection)
        {
            using (SqliteCommand command = connection.CreateCommand())
            {
                command.CommandText = "SELECT last_insert_rowid()";
                return Convert.ToInt32(command.ExecuteScalar());
            }
        }

